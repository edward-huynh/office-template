import { createReadStream, type ReadStream } from 'node:fs';
import fs from 'node:fs/promises';
import path from 'node:path';
import { ApiError } from '../../shared/errors/api-error.js';

/** Read side of a store. The document service only ever receives this for templates. */
export interface ReadableStore {
  read(key: string): Promise<Buffer>;
  openStream(key: string): ReadStream;
  stat(key: string): Promise<{ size: number }>;
  exists(key: string): Promise<boolean>;
}

/** Full store. Replace `LocalFileStore` with an S3 implementation to change backends. */
export interface FileStore extends ReadableStore {
  write(key: string, data: Buffer): Promise<void>;
  remove(key: string): Promise<void>;
  asReadOnly(): ReadableStore;
}

/**
 * File store rooted at a directory. Keys are generated by the server, but every key is still
 * resolved against the root to rule out path traversal.
 */
export class LocalFileStore implements FileStore {
  constructor(private readonly root: string) {}

  resolve(key: string): string {
    if (!key || key.includes('\0') || path.isAbsolute(key)) {
      throw ApiError.badRequest('Invalid storage key');
    }
    const resolved = path.resolve(this.root, key);
    const relative = path.relative(this.root, resolved);
    if (relative.startsWith('..') || path.isAbsolute(relative) || relative === '') {
      throw ApiError.badRequest('Invalid storage key');
    }
    return resolved;
  }

  async read(key: string): Promise<Buffer> {
    return fs.readFile(this.resolve(key));
  }

  openStream(key: string): ReadStream {
    return createReadStream(this.resolve(key));
  }

  async stat(key: string): Promise<{ size: number }> {
    const { size } = await fs.stat(this.resolve(key));
    return { size };
  }

  async exists(key: string): Promise<boolean> {
    try {
      await fs.access(this.resolve(key));
      return true;
    } catch {
      return false;
    }
  }

  async write(key: string, data: Buffer): Promise<void> {
    const target = this.resolve(key);
    await fs.mkdir(path.dirname(target), { recursive: true });
    // Write to a temporary file first so a failed write never leaves a truncated document.
    const temp = `${target}.${process.pid}.${Date.now()}.tmp`;
    await fs.writeFile(temp, data);
    await fs.rename(temp, target);
  }

  async remove(key: string): Promise<void> {
    await fs.rm(this.resolve(key), { force: true });
  }

  asReadOnly(): ReadableStore {
    return {
      read: (key) => this.read(key),
      openStream: (key) => this.openStream(key),
      stat: (key) => this.stat(key),
      exists: (key) => this.exists(key),
    };
  }
}

/** Copies `fromKey` of a readable store into `toKey` of a writable one. */
export async function copyBetween(
  from: ReadableStore,
  fromKey: string,
  to: FileStore,
  toKey: string,
): Promise<number> {
  const data = await from.read(fromKey);
  await to.write(toKey, data);
  return data.byteLength;
}
